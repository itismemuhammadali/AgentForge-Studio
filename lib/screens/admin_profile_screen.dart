      Provider.of<UserProvider>(context, listen: false)
          .updateFirstName(_firstNameController.text);
    });

    _lastNameController.addListener(() {
      Provider.of<UserProvider>(context, listen: false)
          .updateLastName(_lastNameController.text);
    });
